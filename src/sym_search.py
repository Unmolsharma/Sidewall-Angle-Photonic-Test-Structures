"""
Priors table and structure search rerun with strip symmetry imposed (the default from 2026-10-27), with
the strip TM index derivatives and the extra rib slabs (300 and 500 nm at 50/110/130/150 nm).

Run from src/ (main environment):  python sym_search.py
Reads   femwell caches (via priors_search / etchdepth_femwell_analysis)
Writes  results_montecarlo/sym_search/data/{priors.json, priors_table.csv, d_prior_sweep.json,
        search.json, search_table.csv, slab_pairs.json, summary_tables.md}

Search, stages C and D, priors none and realistic:
  - one partial etch: exhaustive best set of each size 1-8 for each slab separately (pool = every strip
    + the ribs of that slab), and the best over all slabs. Slabs 70 and 90 offer four rib widths, the
    others two (300, 500 nm), so the per-slab comparison is also given with 300 and 500 nm only.
  - strips only: exhaustive (expected unidentifiable for every set under the symmetry)
  - two-width rib sets: strip TE (5 widths) + rib 300 + rib 500 nm at each slab (best slab for a
    two-width set), and at 70/90 nm every pair of rib widths
The 'any slabs' search of priors_search.py is not repeated: with 26 candidates it is ~2.4 M sets per
stage and prior.
"""
import csv
import itertools
import json
import os

import numpy as np

import etchdepth_femwell_analysis as ed
import priors_search as ps

OUT = os.path.join(ed.REPO, 'results_montecarlo', 'sym_search', 'data')
SLABS = (50, 70, 90, 110, 130, 150)
STRIP5 = [f'strip_TE_{w}' for w in (400, 450, 500, 550, 600)]
RM = ('ring', 'mzi')


def g(x):
    return '∞' if x == float('inf') else f'{x:.3g}'


def slab_of(u):
    return int(u.split('slab')[1]) if 'slab' in u else None


def restricted(Dall, keep):
    return {u: D for u, D in Dall.items() if keep(u)}


def one_etch(Dall, stage, prior, widths=None):
    """Exhaustive best set per size, per slab; widths restricts the rib widths offered."""
    per_slab = {}
    for s in SLABS:
        keep = lambda u: u.startswith('strip') or (slab_of(u) == s and (widths is None or int(u.split('_')[2]) in widths))
        D = restricted(Dall, keep)
        if not any(slab_of(u) == s for u in ps.eligible(D, stage)):
            continue
        pool, best, steps, cand = ps.search(D, stage, ps.PRIORS[prior], 'one partial etch')
        per_slab[s] = {}
        for k, (a, combo) in best.items():
            v, lo, hi = ps.rng(ps.evaluate([cand[u] for u in combo], Dall, stage, ps.PRIORS[prior]))
            per_slab[s][k] = dict(set=list(combo), a_deg_h=v, a_deg_min=lo, a_deg_max=hi)
        per_slab[s]['pool'] = pool
        per_slab[s]['greedy'] = steps
    overall = {}
    for k in range(1, 9):
        c = [(d[k]['a_deg_h'], s) for s, d in per_slab.items() if k in d]
        if c:
            a, s = min(c)
            overall[k] = dict(per_slab[s][k], slab=s)
    return per_slab, overall


def strips_only(Dall, stage, prior):
    pool, best, steps, cand = ps.search(Dall, stage, ps.PRIORS[prior], 'strips only')
    return {k: dict(set=list(combo), a_deg_h=a) for k, (a, combo) in best.items()}


def slab_pairs(Dall):
    out = {}
    for stage in ('C', 'D'):
        for prior in ('none', 'realistic'):
            el = set(ps.eligible(Dall, stage))
            res = {}
            for s in SLABS:
                ribs = [f'rib_TE_{w}_slab{s}' for w in (300, 400, 500, 600) if f'rib_TE_{w}_slab{s}' in el]
                for pair in itertools.combinations(ribs, 2):
                    items = [(u, RM) for u in STRIP5 + list(pair)]
                    v, lo, hi = ps.rng(ps.evaluate(items, Dall, stage, ps.PRIORS[prior]))
                    res[' + '.join(pair)] = dict(slab=s, a_deg_h=v, a_deg_min=lo, a_deg_max=hi)
                single = [f'rib_TE_{w}_slab{s}' for w in (500,) if f'rib_TE_{w}_slab{s}' in el]
                for r in single:
                    items = [(u, RM) for u in STRIP5 + [r]]
                    v, lo, hi = ps.rng(ps.evaluate(items, Dall, stage, ps.PRIORS[prior]))
                    res[r] = dict(slab=s, a_deg_h=v, a_deg_min=lo, a_deg_max=hi)
            out[f'{stage}|{prior}'] = res
    return out


def tables(search, pairs):
    L = ['<!-- generated by src/sym_search.py; do not edit -->']
    L.append('\n## S1. Strip TE (5 widths) + two rib widths (300 + 500 nm) at each slab, strip symmetry imposed '
             '(strip-angle CRB at h [min–max over h/2, h, 2h], deg)\n')
    L.append('| Slab (nm) | C, none | C, realistic | D, none | D, realistic |')
    L.append('|---|---|---|---|---|')
    for s in SLABS:
        key = f'rib_TE_300_slab{s} + rib_TE_500_slab{s}'
        cells = []
        for tag in ('C|none', 'C|realistic', 'D|none', 'D|realistic'):
            e = pairs[tag].get(key)
            cells.append(f"{g(e['a_deg_h'])} [{g(e['a_deg_min'])}–{g(e['a_deg_max'])}]" if e else 'n/a')
        L.append(f'| {s} | ' + ' | '.join(cells) + ' |')
    L.append('\n## S2. Strip TE (5) + one rib (500 nm) at each slab (strip-angle CRB at h, deg)\n')
    L.append('| Slab (nm) | C, none | C, realistic | D, none | D, realistic |')
    L.append('|---|---|---|---|---|')
    for s in SLABS:
        cells = [g(pairs[t][f'rib_TE_500_slab{s}']['a_deg_h']) if f'rib_TE_500_slab{s}' in pairs[t] else 'n/a'
                 for t in ('C|none', 'C|realistic', 'D|none', 'D|realistic')]
        L.append(f'| {s} | ' + ' | '.join(cells) + ' |')
    for tag, ent in search.items():
        st, pr = tag.split('|')
        L.append(f'\n## S3-{st}-{pr}. Best one-etch set of 8 per slab, stage {st}, priors {pr} (deg)\n')
        L.append('| Slab | all widths offered | set | 300 + 500 nm only | set |')
        L.append('|---|---|---|---|---|')
        for s in SLABS:
            a = ent['one_etch_per_slab'].get(str(s), {}).get('8')
            b = ent['one_etch_per_slab_300_500'].get(str(s), {}).get('8')
            sh = lambda e: ' + '.join(x.replace('strip_', '').replace('rib_TE_', 'rib ').replace('_slab', ' s') for x in e['set'])
            L.append(f"| {s} | {g(a['a_deg_h']) if a else 'n/a'} | {sh(a) if a else ''} | "
                     f"{g(b['a_deg_h']) if b else 'n/a'} | {sh(b) if b else ''} |")
        L.append(f'\nBest one-etch set by size, all slabs (stage {st}, priors {pr}):\n')
        L.append('| k | CRB at h [min–max] | slab | set | strips only |')
        L.append('|---|---|---|---|---|')
        for k in map(str, range(1, 9)):
            e = ent['one_etch_overall'].get(k)
            so = ent['strips_only'].get(k)
            if e:
                L.append(f"| {k} | {g(e['a_deg_h'])} [{g(e['a_deg_min'])}–{g(e['a_deg_max'])}] | {e['slab']} | "
                         f"{' + '.join(e['set'])} | {g(so['a_deg_h']) if so else 'n/a'} |")
    return '\n'.join(L) + '\n'


def main():
    os.makedirs(OUT, exist_ok=True)
    Dall = ps.derivatives(ed.load())             # strip symmetry imposed (default)
    ps.OUT = os.path.dirname(OUT)                # priors_search writes to <ps.OUT>/data/
    ps.run_priors(Dall)                          # same sets as results_priors_search, now symmetric
    ps.run_dsweep(Dall)
    search, rows = {}, []
    for stage in ('C', 'D'):
        for prior in ('none', 'realistic'):
            per, overall = one_etch(Dall, stage, prior)
            per35, _ = one_etch(Dall, stage, prior, widths=(300, 500))
            so = strips_only(Dall, stage, prior)
            tag = f'{stage}|{prior}'
            search[tag] = dict(one_etch_per_slab={str(s): {str(k): v for k, v in d.items()} for s, d in per.items()},
                               one_etch_per_slab_300_500={str(s): {str(k): v for k, v in d.items()} for s, d in per35.items()},
                               one_etch_overall={str(k): v for k, v in overall.items()},
                               strips_only={str(k): v for k, v in so.items()})
            for k, e in overall.items():
                rows.append(dict(search=tag, kind='one etch, best over slabs', k=k, slab=e['slab'],
                                 set=' + '.join(e['set']), a_deg_h=e['a_deg_h'], a_deg_min=e['a_deg_min'], a_deg_max=e['a_deg_max']))
            for s, d in per.items():
                for k in range(1, 9):
                    if k in d:
                        rows.append(dict(search=tag, kind='one etch, per slab', k=k, slab=s, set=' + '.join(d[k]['set']),
                                         a_deg_h=d[k]['a_deg_h'], a_deg_min=d[k]['a_deg_min'], a_deg_max=d[k]['a_deg_max']))
            print(f'{tag}: best one-etch 8 -> {overall[8]["a_deg_h"]:.4g} at slab {overall[8]["slab"]}: {overall[8]["set"]}')
            print(f'{tag}: strips only best ->', {k: v['a_deg_h'] for k, v in so.items()})
    pairs = slab_pairs(Dall)
    for tag, r in pairs.items():
        print(tag, {k: round(v['a_deg_h'], 4) for k, v in r.items() if '300' in k and '500' in k})
    with open(os.path.join(OUT, 'search.json'), 'w') as f:
        json.dump(search, f, indent=1)
    with open(os.path.join(OUT, 'search_table.csv'), 'w', newline='') as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        w.writeheader()
        w.writerows(rows)
    with open(os.path.join(OUT, 'slab_pairs.json'), 'w') as f:
        json.dump(pairs, f, indent=1)
    with open(os.path.join(OUT, 'summary_tables.md'), 'w', encoding='utf-8') as f:
        f.write(tables(search, pairs))


if __name__ == '__main__':
    main()
