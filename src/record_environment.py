"""
Record the software environment, solver settings and random seeds, read from the installed packages and the
source code (nothing typed by hand).

Run from src/ (main environment):  python record_environment.py
Writes results_final/data/environment.json and results_final/ENVIRONMENT.md
"""
import inspect
import json
import os
import platform
import subprocess
import sys
from importlib import metadata

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(REPO, 'results_final')
VENV = 'C:/Users/unmol/.venvs/femwell/Scripts/python.exe'
PKGS_MAIN = ['numpy', 'scipy', 'ElectroMagneticPython', 'matplotlib']
PKGS_FEM = ['femwell', 'scikit-fem', 'numpy', 'scipy', 'gmsh', 'shapely', 'meshio']

FEM_PROBE = r'''
import json, sys, inspect, platform
from importlib import metadata
sys.path.insert(0, sys.argv[1])
import femwell_batch as fb
def v(p):
    try: return metadata.version(p)
    except Exception as e: return 'not installed'
src = inspect.getsource(fb.solve) + inspect.getsource(fb.build) + inspect.getsource(fb.pick)
print(json.dumps(dict(python=sys.version.split()[0], executable=sys.executable,
    packages={p: v(p) for p in json.loads(sys.argv[2])},
    constants=dict(MESH=fb.MESH, WLS=fb.WLS, DLAM_um=fb.DLAM, H=fb.H, FACTORS=fb.FACTORS, N_SI=fb.N_SI, N_OX=fb.N_OX,
                   N_AIR=fb.N_AIR, WL0_um=fb.WL0, SLAB0_um=fb.SLAB0, POWER_CHECK_S=fb.POWER_CHECK_S),
    solver_source=src)))
'''


def version(p):
    try:
        return metadata.version(p)
    except metadata.PackageNotFoundError:
        return 'not installed'


def main():
    os.makedirs(os.path.join(OUT, 'data'), exist_ok=True)
    fem = json.loads(subprocess.run([VENV, '-c', FEM_PROBE, os.path.join(REPO, 'src'), json.dumps(PKGS_FEM)],
                                    capture_output=True, text=True, check=True).stdout)
    import montecarlo as mc
    import robustness_rib300 as rr
    import strips_angle_info as sa
    import etchdepth_femwell_analysis as ed
    import noise_sourced as nsrc
    seeds = dict(
        montecarlo_SEED=mc.SEED, montecarlo_note='LHS design: qmc.LatinHypercube(seed=SEED); noise sets: '
        'default_rng([SEED, ord(case), chunk]); bootstrap: default_rng(SEED)',
        robustness_rib300_SEED=rr.SEED, robustness_note='default_rng([SEED, int(1000 p), len(set name)])',
        strips_angle_info='default_rng(20261027) (in strips_angle_info.main, perturbation draws)',
        provenance_audit='chance-match test default_rng(1)')
    git = subprocess.run(['git', 'rev-parse', 'HEAD'], cwd=REPO, capture_output=True, text=True).stdout.strip()
    env = dict(
        git_head_when_recorded=git, platform=platform.platform(), processor=platform.processor(),
        main=dict(python=sys.version.split()[0], executable=sys.executable, packages={p: version(p) for p in PKGS_MAIN}),
        femwell_env=fem,
        analysis_constants=dict(T_STRIP_nm=ed.T_STRIP, H_steps=ed.H, FACTORS=ed.FACTORS, WL0_um=ed.WL0, DLAM_um=ed.DLAM,
                                DNDT_SI=ed.DNDT_SI, DNDT_OX=ed.DNDT_OX,
                                placeholder_noise=dict(SIGMA_NEFF=6.5e-6, SIGMA_NG=1e-3, SIGMA_PHASE=1e-3, L_MZI_um=100.0),
                                sourced_noise_levels_m=dict(primary_1pm=1e-12, best_case_0p1pm=1e-13),
                                noise_conversion=dict(n_g=nsrc.NG, L_m=nsrc.L, lambda_m=nsrc.LAM),
                                montecarlo=dict(NSETS=mc.NSETS, NSTART=mc.NSTART, K_BOX=mc.K_BOX, N_TRAIN=mc.N_TRAIN,
                                                N_TEST=mc.N_TEST, CHUNK=mc.CHUNK)),
        seeds=seeds)
    with open(os.path.join(OUT, 'data', 'environment.json'), 'w') as f:
        json.dump(env, f, indent=1)
    c = fem['constants']
    L = ['<!-- generated by src/record_environment.py; do not edit -->', '# Environment', '',
         f"Recorded at git commit `{git}` on `{env['platform']}`.", '',
         '## Software', '', '| Environment | Python | Packages |', '|---|---|---|',
         f"| main (analysis) | {env['main']['python']} | " + ', '.join(f'{k} {v}' for k, v in env['main']['packages'].items()) + ' |',
         f"| femwell (solves) | {fem['python']} | " + ', '.join(f'{k} {v}' for k, v in fem['packages'].items()) + ' |',
         '', '## Solver settings (from `src/femwell_batch.py`)', '',
         f"- Mesh r12: core resolution {c['MESH']['r12'][0]} um, distance {c['MESH']['r12'][1]} um, max {c['MESH']['r12'][2]} um "
         f"(r8 check: {c['MESH']['r8'][0]} um).",
         f"- Wavelengths {c['WLS']} um (n_g by central difference, d lambda = {c['DLAM_um']} um).",
         f"- Materials: n_Si {c['N_SI']}, n_ox {c['N_OX']}, air {c['N_AIR']}; no dispersion. Default rib slab {c['SLAB0_um']} um.",
         f"- Finite-difference steps h: {c['H']} (nm, deg, index), at factors {c['FACTORS']}.",
         f"- Power check every {c['POWER_CHECK_S']} s during runs.",
         '- Domain, mode search and polarization selection: the source of `solve`, `build` and `pick` is stored '
         'verbatim in `data/environment.json` (`femwell_env.solver_source`).',
         '', '## Analysis constants', '',
         '| Constant | Value |', '|---|---|']
    for k, v in env['analysis_constants'].items():
        L.append(f'| {k} | `{json.dumps(v)}` |')
    L += ['', '## Random seeds', '', '| Where | Seed / scheme |', '|---|---|']
    L += [f'| {k} | {v} |' for k, v in seeds.items()]
    with open(os.path.join(OUT, 'ENVIRONMENT.md'), 'w', encoding='utf-8') as f:
        f.write('\n'.join(L) + '\n')
    print('\n'.join(L[:12]))


if __name__ == '__main__':
    main()
