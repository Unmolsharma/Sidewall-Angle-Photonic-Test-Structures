"""
Markdown tables for results_priors_search/SUMMARY.md, built only from the files priors_search.py writes.

Run from src/:  python priors_search_tables.py
Reads   results_priors_search/data/{priors_table.csv, d_prior_sweep.json, search.json}
Writes  results_priors_search/data/summary_tables.md
"""
import csv
import json
import os

D = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), 'results_priors_search', 'data')
SETS = ['strip alone', 'strip + rib70 (500 nm)', 'strip + rib70 (500 + 300 nm)']
PRI = ['none', 'd 1 nm', 'd 2 nm', 'd 5 nm', 'n_Si 1e-3', 'n_Si 1e-4', 'n_ox 1e-3', 'n_ox 1e-4', 'n_Si, n_ox 1e-3',
       'n_Si, n_ox 1e-4', 'ar-a 1 deg', 'ar-a 2 deg', 'ar-a 5 deg', 'T 1 K', 'realistic', 'realistic + ar-a 2 deg',
       'all optimistic']


def g(x):
    return '∞' if float(x) == float('inf') else f'{float(x):.3g}'


def short(u):
    return u.replace('strip_', '').replace('rib_TE_', 'rib ').replace('_slab', ' s')


def main():
    rows = list(csv.DictReader(open(os.path.join(D, 'priors_table.csv'))))
    get = lambda st, p, s, m='1.0': next(r for r in rows if r['stage'] == st and r['prior'] == p and r['set'] == s and r['rib_mult'] == m)
    L = ['<!-- generated by src/priors_search_tables.py; do not edit -->']
    L.append('\n## T1. Single pieces of outside knowledge, stages D and E (strip-angle CRB at h, deg; gain = no prior / with prior)\n')
    L.append('| Prior | D: strip + rib70 | gain | D: strip + 2 rib widths | gain | E: strip + rib70 | gain | E: strip + 2 rib widths | gain |')
    L.append('|---|---|---|---|---|---|---|---|---|')
    for p in PRI[1:]:
        cells = []
        for st in 'DE':
            for s in SETS[1:]:
                v, n = float(get(st, p, s)['a_deg_h']), float(get(st, 'none', s)['a_deg_h'])
                cells += [g(v), f'{n / v:.2f}x']
        L.append(f'| {p} | ' + ' | '.join(cells) + ' |')
    L.append('\n## T2. Rib vs strip alone under the same priors (ratio = strip alone / set, at h; rib noise 1.0x, last column 0.2x)\n')
    L.append('| Stage | Prior | strip alone | + rib70 | ratio | + 2 rib widths | ratio | + 2 rib widths, rib noise 0.2x |')
    L.append('|---|---|---|---|---|---|---|---|')
    for st in 'BCDE':
        for p in ('none', 'realistic', 'realistic + ar-a 2 deg', 'all optimistic'):
            a, b, c = (float(get(st, p, s)['a_deg_h']) for s in SETS)
            o = float(get(st, p, SETS[2], '0.2')['a_deg_h'])
            L.append(f'| {st} | {p} | {g(a)} | {g(b)} | {a / b:.2f}x | {g(c)} | {a / c:.1f}x | {g(o)} |')
    for st in 'BCDE':
        L.append(f'\n## T3-{st}. Every prior, stage {st} (strip-angle CRB at h [min–max over h/2, h, 2h], deg)\n')
        L.append('| Prior | ' + ' | '.join(SETS) + ' |')
        L.append('|---|---|---|---|')
        for p in PRI:
            L.append(f'| {p} | ' + ' | '.join(f"{g(x['a_deg_h'])} [{g(x['a_deg_min'])}–{g(x['a_deg_max'])}]"
                                              for x in (get(st, p, s) for s in SETS)) + ' |')
    sw = json.load(open(os.path.join(D, 'd_prior_sweep.json')))
    L.append('\n## T4. Etch-depth prior sweep (strip-angle CRB at h, deg)\n')
    L.append('| Stage | Set | 0.01 nm | 0.03 | 0.1 | 0.3 | 1 | 2 | 5 | free | depth known (A*) |')
    L.append('|---|---|---|---|---|---|---|---|---|---|---|')
    for st in 'BC':
        for s, v in sw[st].items():
            L.append(f'| {st} | {s} | ' + ' | '.join(g(v[k]['a_deg_h']) for k in ('0.01', '0.03', '0.1', '0.3', '1.0', '2.0', '5.0', 'free'))
                     + f" | {g(sw['A* (depth known)'][s]['a_deg_h'])} |")
    S = json.load(open(os.path.join(D, 'search.json')))
    f = lambda b: f"{g(b['a_deg_h'])} [{g(b['a_deg_min'])}–{g(b['a_deg_max'])}]" if b else 'n/a'
    for st in 'CD':
        for p in ('none', 'realistic'):
            L.append(f'\n## T5-{st}-{p}. Exhaustive best sets, stage {st}, priors: {p} (strip-angle CRB at h [min–max], deg)\n')
            L.append('| k | strips only | one partial etch | best one-etch set | λmin (one etch) | any slabs |')
            L.append('|---|---|---|---|---|---|')
            for k in map(str, range(1, 9)):
                so = S[f'{st}|{p}|strips only']['best'].get(k)
                oe = S[f'{st}|{p}|one partial etch']['best'][k]
                an = S[f'{st}|{p}|any slabs']['best'][k]
                L.append(f"| {k} | {f(so)} | {f(oe)} | {' + '.join(short(u) for u in oe['set'])} | {oe['eig_min_h']:.2g} | {f(an)} |")
            e = S[f'{st}|{p}|one partial etch']['greedy']
            L.append('\nGreedy, one partial etch: ' + ' → '.join(
                f"+{short(x['added'])} {g(x['a_deg_h'])} (λmin {x['eig_min_h']:.2g})" for x in e))
    with open(os.path.join(D, 'summary_tables.md'), 'w', encoding='utf-8') as fo:
        fo.write('\n'.join(L) + '\n')


if __name__ == '__main__':
    main()
