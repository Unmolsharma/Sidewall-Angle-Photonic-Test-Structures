"""Tables of the practical-feasibility section, written from results_review/data/feasibility.json:
    paper/sections/tab_local.tex        bound at every level of the local-variation grid (N = 1)
    paper/sections/tab_replication.tex  bound versus the number of copies, and N for 1.5x and 2x

Run:  python paper/scripts/make_tables.py
"""
import os

import style

SEC = os.path.join(style.REPO, 'paper', 'sections')
WIDTHS = (0.1, 0.3, 0.6, 1.0)
ANGLES = (0.1, 0.3, 0.5, 1.0)
THICK = (0.1, 0.3)
NAMES = {'two': 'Two-width set', 'best': 'Best set of 8'}


def f3(x):
    return f'{x:.3g}' if x < 100 else f'{x:.0f}'


def local(R):
    L = ['% generated by paper/scripts/make_tables.py from results_review/data/feasibility.json; do not edit',
         r'\begin{table*}[!t]',
         r'\caption{Strip-angle CRLB $\sth$ (\si{\degree}) of one copy of each set when every structure has independent offsets of '
         r'width ($\sigma_w$), sidewall angle ($\sigma_\theta$) and thickness ($\sigma_t$), stage~D, realistic priors, \qty{1}{pm}, ring and '
         r'MZI. Shared-parameter bounds: \qty{' + f"{R['two']['ring_mzi']['shared']:.4g}" + r'}{\degree} (two-width) and \qty{' +
         f"{R['best']['ring_mzi']['shared']:.3g}" + r'}{\degree} (best set of eight). Rings alone give the same values to three digits. '
         r'The angle levels are assumed, and so are the width levels below \qty{0.6}{nm} and the thickness level of \qty{0.1}{nm} '
         r'(Section~\ref{sec:replication}).}',
         r'\label{tab:local}', r'\centering', r'\begin{tabular}{@{}lc' + 'cccc' * 2 + '@{}}', r'\toprule',
         r' & & \multicolumn{4}{c}{$\sigma_t=\qty{0.1}{nm}$} & \multicolumn{4}{c}{$\sigma_t=\qty{0.3}{nm}$} \\',
         r'Set & $\sigma_w$ (nm) & ' + ' & '.join(rf'$\sigma_\theta={a:g}$' for a in ANGLES * 2) + r' \\', r'\midrule']
    for n in ('two', 'best'):
        g = R[n]['ring_mzi']['grid']
        for i, w in enumerate(WIDTHS):
            vals = [[x['bound_deg'] for x in g if x['thickness_nm'] == t and x['width_nm'] == w and x['angle_deg'] == a][0]
                    for t in THICK for a in ANGLES]
            L.append((NAMES[n] if i == 0 else '') + f' & {w:g} & ' + ' & '.join(f3(v) for v in vals) + r' \\')
        if n == 'two':
            L.append(r'\midrule')
    L += [r'\bottomrule', r'\end{tabular}', r'\end{table*}', '']
    open(os.path.join(SEC, 'tab_local.tex'), 'w', encoding='utf-8').write('\n'.join(L))


def replication(R):
    copies = ('1', '4', '16', '64', '256')
    L = ['% generated by paper/scripts/make_tables.py from results_review/data/feasibility.json; do not edit',
         r'\begin{table*}[!t]',
         r'\caption{Strip-angle CRLB $\sth$ (\si{\degree}) when each structure is repeated $N$ times and all copies are fitted jointly, with '
         r'shared process parameters and independent local offsets (stage~D, realistic priors, \qty{1}{pm}, ring and MZI). The last two columns give '
         r'the $N$ that returns the bound to 1.5 and 2 times the shared-parameter bound of one copy; rings-only values are in parentheses.}',
         r'\label{tab:replication}', r'\centering', r'\begin{tabular}{@{}lccc' + 'c' * 5 + 'cc@{}}', r'\toprule',
         r'Set & $\sigma_w$ (nm) & $\sigma_\theta$ (\si{\degree}) & $\sigma_t$ (nm) & ' + ' & '.join(f'$N={c}$' for c in copies) +
         r' & $N$ for $1.5\times$ & $N$ for $2\times$ \\', r'\midrule']
    for n in ('two', 'best'):
        r, ro = R[n]['ring_mzi'], R[n]['ring']
        L.append(NAMES[n] + r', shared & -- & -- & -- & ' + ' & '.join(f3(r['shared_same_N'][c]) for c in copies) + r' & -- & -- \\')
        for s, d in r['scenarios'].items():
            q = ro['scenarios'][s]
            L.append(f" & {d['width_nm']:g} & {d['angle_deg']:g} & {d['thickness_nm']:g} & " + ' & '.join(f3(d['bound'][c]) for c in copies) +
                     f" & {d['N_1p5']} ({q['N_1p5']}) & {d['N_2']} ({q['N_2']})" + r' \\')
        if n == 'two':
            L.append(r'\midrule')
    L += [r'\bottomrule', r'\end{tabular}', r'\end{table*}', '']
    open(os.path.join(SEC, 'tab_replication.tex'), 'w', encoding='utf-8').write('\n'.join(L))


if __name__ == '__main__':
    F = style.load('results_review/data/feasibility.json')
    local(F['variation'])
    replication(F['replication'])
    print('wrote tab_local.tex, tab_replication.tex')
