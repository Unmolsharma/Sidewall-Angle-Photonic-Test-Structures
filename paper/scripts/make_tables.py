"""Tables of the practical-feasibility section, written from results_review/data/feasibility.json:
    paper/sections/tab_local.tex        bound at every level of the local-variation grid (N = 1)
    paper/sections/tab_replication.tex  bound versus the number of copies, and N for 1.5x and 2x

Run:  python paper/scripts/make_tables.py
"""
import os

import style

SEC = os.path.join(style.REPO, 'paper', 'sections')
WIDTHS = (0.1, 0.3, 0.6, 1.0)
ANGLES = (0.1, 0.3, 0.5, 1.0)
THICK = (0.1, 0.3)
NAMES = {'two': 'Two-width set', 'best': 'Best set of 8'}


def f3(x):
    return f'{x:.3g}' if x < 100 else f'{x:.0f}'


def local(R):
    L = ['% generated by paper/scripts/make_tables.py from results_review/data/feasibility.json; do not edit',
         r'\begin{table*}[!t]',
         r'\caption{Strip-angle CRLB $\sth$ (\si{\degree}) of one copy of each set when every structure has independent offsets of '
         r'width ($\sigma_w$), sidewall angle ($\sigma_\theta$) and thickness ($\sigma_t$), stage~D, realistic priors, \qty{1}{pm}, ring and '
         r'MZI. Shared-parameter bounds: \qty{' + f"{R['two']['ring_mzi']['shared']:.4g}" + r'}{\degree} (two-width) and \qty{' +
         f"{R['best']['ring_mzi']['shared']:.3g}" + r'}{\degree} (best set of eight). Rings alone give the same values to three digits. '
         r'The angle levels are assumed, and so are the width levels below \qty{0.6}{nm} and the thickness level of \qty{0.1}{nm} '
         r'(Section~\ref{sec:replication}).}',
         r'\label{tab:local}', r'\centering', r'\begin{tabular}{@{}lc' + 'cccc' * 2 + '@{}}', r'\toprule',
         r' & & \multicolumn{4}{c}{$\sigma_t=\qty{0.1}{nm}$} & \multicolumn{4}{c}{$\sigma_t=\qty{0.3}{nm}$} \\',
         r'Set & $\sigma_w$ (nm) & ' + ' & '.join(rf'$\sigma_\theta={a:g}$' for a in ANGLES * 2) + r' \\', r'\midrule']
    for n in ('two', 'best'):
        g = R[n]['ring_mzi']['grid']
        for i, w in enumerate(WIDTHS):
            vals = [[x['bound_deg'] for x in g if x['thickness_nm'] == t and x['width_nm'] == w and x['angle_deg'] == a][0]
                    for t in THICK for a in ANGLES]
            L.append((NAMES[n] if i == 0 else '') + f' & {w:g} & ' + ' & '.join(f3(v) for v in vals) + r' \\')
        if n == 'two':
            L.append(r'\midrule')
    L += [r'\bottomrule', r'\end{tabular}', r'\end{table*}', '']
    open(os.path.join(SEC, 'tab_local.tex'), 'w', encoding='utf-8').write('\n'.join(L))


def replication(R):
    copies = ('1', '4', '16', '64', '256')
    L = ['% generated by paper/scripts/make_tables.py from results_review/data/feasibility.json; do not edit',
         r'\begin{table*}[!t]',
         r'\caption{Strip-angle CRLB $\sth$ (\si{\degree}) when each structure is repeated $N$ times and all copies are fitted jointly, with '
         r'shared process parameters and independent local offsets (stage~D, realistic priors, \qty{1}{pm}, ring and MZI). The last two columns give '
         r'the $N$ that returns the bound to 1.5 and 2 times the shared-parameter bound of one copy; rings-only values are in parentheses.}',
         r'\label{tab:replication}', r'\centering', r'\begin{tabular}{@{}lccc' + 'c' * 5 + 'cc@{}}', r'\toprule',
         r'Set & $\sigma_w$ (nm) & $\sigma_\theta$ (\si{\degree}) & $\sigma_t$ (nm) & ' + ' & '.join(f'$N={c}$' for c in copies) +
         r' & $N$ for $1.5\times$ & $N$ for $2\times$ \\', r'\midrule']
    for n in ('two', 'best'):
        r, ro = R[n]['ring_mzi'], R[n]['ring']
        L.append(NAMES[n] + r', shared & -- & -- & -- & ' + ' & '.join(f3(r['shared_same_N'][c]) for c in copies) + r' & -- & -- \\')
        for s, d in r['scenarios'].items():
            q = ro['scenarios'][s]
            L.append(f" & {d['width_nm']:g} & {d['angle_deg']:g} & {d['thickness_nm']:g} & " + ' & '.join(f3(d['bound'][c]) for c in copies) +
                     f" & {d['N_1p5']} ({q['N_1p5']}) & {d['N_2']} ({q['N_2']})" + r' \\')
        if n == 'two':
            L.append(r'\midrule')
    L += [r'\bottomrule', r'\end{tabular}', r'\end{table*}', '']
    open(os.path.join(SEC, 'tab_replication.tex'), 'w', encoding='utf-8').write('\n'.join(L))


MODELS = [('lin_all', 'Linear, strips and ribs'), ('quad_all', 'Quadratic, strips and ribs'), ('lin_strip', 'Linear, strips only'),
          ('quad_strip', 'Quadratic, strips only'), ('rib_offset', 'Rib offset from strips'), ('rib_offset_lin', 'Own offset per rib width'),
          ('per_design', 'Own offset per design')]


def systematic(Y):
    r = Y['systematic']['ring_mzi']
    pri = ('none', '0.01', '0.03', '0.1', '0.3', '1')
    L = ['% generated by paper/scripts/make_tables.py from results_review/data/systematic.json; do not edit',
         r'\begin{table}[!t]',
         r'\caption{Strip-angle CRLB $\sth$ (\si{\degree}) of the two-width set when the width offset depends on the drawn width (systematic, the same in '
         r'every copy) and its coefficients are fitted, without a prior or with the prior standard deviation shown (nm, per \qty{100}{nm} of width for the '
         r'linear and per $(\qty{100}{nm})^2$ for the quadratic coefficient). Stage~D, realistic priors, \qty{1}{pm}, ring and MZI; no systematic term: '
         r'\qty{' + f"{r['shared']:.4g}" + r'}{\degree}.}',
         r'\label{tab:systematic}', r'\centering', r'\setlength{\tabcolsep}{2.5pt}', r'\begin{tabular}{@{}l' + 'c' * len(pri) + '@{}}', r'\toprule',
         r'Width offset & none & ' + ' & '.join(pri[1:]) + r' \\', r'\midrule']
    for m, lab in MODELS:
        L.append(lab + ' & ' + ' & '.join(r'$\infty$' if r['models'][m][p] == float('inf') else f3(r['models'][m][p]) for p in pri) + r' \\')
    L += [r'\bottomrule', r'\end{tabular}', r'\end{table}', '']
    open(os.path.join(SEC, 'tab_systematic.tex'), 'w', encoding='utf-8').write('\n'.join(L))


def correlation(Y):
    C = Y['correlation']
    S, Ls = C['s_mm'], C['L_mm']
    n = lambda x: '$>256$' if x is None else str(x)
    L = ['% generated by paper/scripts/make_tables.py from results_review/data/systematic.json; do not edit',
         r'\begin{table}[!t]',
         r'\caption{Copies of each structure needed to return the two-width bound to 2 times (1.5 times in parentheses) the shared-parameter bound, when the local '
         r'offsets (\qty{0.3}{nm}, \qty{0.3}{\degree}, \qty{0.1}{nm}) are correlated as $\exp(-d/L)$. Copies sit in cells of pitch $s$, one copy of each design per cell. '
         r'Field: one random field for all structures; same design: correlation only between copies of one design. Independent offsets need 34 (61). '
         r'The correlation lengths are assumed.}',
         r'\label{tab:correlation}', r'\centering', r'\setlength{\tabcolsep}{3pt}', r'\begin{tabular}{@{}lc' + 'c' * len(S) + '@{}}', r'\toprule',
         r' & & \multicolumn{' + str(len(S)) + r'}{c}{copy spacing $s$ (mm)} \\', r'Model & $L$ (mm) & ' + ' & '.join(f'{s:g}' for s in S) + r' \\', r'\midrule']
    for mode, lab in (('field', 'Field'), ('same_design', 'Same design')):
        for k, l in enumerate(Ls):
            cs = [C['cases'][f'{mode}|L={l:g}|s={s:g}'] for s in S]
            L.append((lab if k == 0 else '') + f' & {l:g} & ' + ' & '.join(f"{n(c['N_2'])} ({n(c['N_1p5'])})" for c in cs) + r' \\')
        if mode == 'field':
            L.append(r'\midrule')
    L += [r'\bottomrule', r'\end{tabular}', r'\end{table}', '']
    open(os.path.join(SEC, 'tab_correlation.tex'), 'w', encoding='utf-8').write('\n'.join(L))


if __name__ == '__main__':
    F = style.load('results_review/data/feasibility.json')
    local(F['variation'])
    replication(F['replication'])
    Y = style.load('results_review/data/systematic.json')
    systematic(Y)
    correlation(Y)
    print('wrote tab_local.tex, tab_replication.tex, tab_systematic.tex, tab_correlation.tex')
